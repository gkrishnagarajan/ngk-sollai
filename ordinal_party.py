_eth_alt = "|".join(re.escape(e) for e in sorted(ETHIRI_SUFFIX, key=len, reverse=True))
PAT_ETHIRI = re.compile(r"(" + _ord_alt + r")(\s+)(" + _eth_alt + r")")

def apply_ordinal_party(text):
    changes = []
    def _repl(m):
        orig = m.group(1)
        repl = ORDINALS[orig]
        changes.append({
            "wrong":    orig,
            "correct":  repl,
            "category": "ordinal_party",
            "source":   "ordinal_party",
        })
        return repl + m.group(2)
    out = PAT.sub(_repl, text)

    # Second pass: ordinal + எதிரி-inflection -> N-ஆம் குற்றஞ்சாட்டப்பட்ட நபர்+suffix
    def _eth_repl(m):
        ord_orig  = m.group(1)
        eth_orig  = m.group(3)
        num       = ORDINALS[ord_orig]
        party     = ETHIRI_SUFFIX[eth_orig]
        result    = num + m.group(2) + party
        changes.append({
            "wrong":    m.group(0),
            "correct":  result,
            "category": "ordinal_party",
            "source":   "ordinal_party",
        })
        return result
    out = PAT_ETHIRI.sub(_eth_repl, out)

    return out, changes

