_series_keys = sorted(SERIES_MAP.keys(), key=len, reverse=True)
_state_keys  = sorted(STATE_MAP.keys(),  key=len, reverse=True)
_SERIES_ALT  = "|".join(re.escape(k) for k in _series_keys)
_STATE_ALT   = "|".join(re.escape(k) for k in _state_keys)

_PAT = re.compile(
    r'(' + _STATE_ALT  + r')'
    r'[\s.]*(\d{1,2})?'
    r'[\s.]+(' + _SERIES_ALT + r')'
    r'[\s.]+(\d{2,4})'
    r'(?:[,\s]+(\d{2}))?',
    re.UNICODE
)

def _make_replacement(m, text):
    state  = STATE_MAP.get(m.group(1), m.group(1).upper())
    dist   = str(int(m.group(2))) if m.group(2) else ""
    series = SERIES_MAP.get(m.group(3), m.group(3).upper())
    number = m.group(4) + (m.group(5) or "")
    parts  = [state]
    if dist:
        parts.append(dist)
    parts.append(series)
    parts.append(number)
    result = ".".join(parts)
    # Insert space when immediately followed by a Tamil letter
    if m.end() < len(text) and TA_START.match(text[m.end()]):
        result += " "
    return result

def normalize_vehicle_reg(text):
    corrections = []
    result = []
    pos = 0
    for m in _PAT.finditer(text):
        result.append(text[pos:m.start()])
        original  = m.group(0)
        corrected = _make_replacement(m, text)
        corrected_bare = corrected.rstrip(" ")
        if original != corrected_bare:
            corrections.append({"original": original, "corrected": corrected_bare,
                                 "start": m.start(), "end": m.end()})
        result.append(corrected)
        pos = m.end()
    result.append(text[pos:])
    return "".join(result), corrections

